"""Generate exact dependency closures from a successfully installed environment.

Run after deliberately resolving the .in files and installing production inputs.
It follows installed metadata, evaluates requested extras, rejects unsatisfied
specifiers, and writes only project-owned requirements. The locks are version
pins (not artifact hashes); portable Linux installs must be verified separately.
"""

from importlib import metadata
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parent.parent
REQUIREMENTS = ROOT / "backend" / "requirements"


def direct_requirements(name: str) -> list[Requirement]:
    """Read direct non-include pins; base inputs are combined explicitly below."""
    return [
        Requirement(line.strip())
        for line in (REQUIREMENTS / name).read_text().splitlines()
        if line.strip() and not line.lstrip().startswith(("#", "-r"))
    ]


def closure(initial: list[Requirement]) -> dict[str, str]:
    """Walk installed transitive requirements with extras and marker evaluation."""
    selected = {}
    seen = set()
    pending = list(initial)
    while pending:
        requirement = pending.pop()
        name = canonicalize_name(requirement.name)
        distribution = metadata.distribution(name)
        if distribution.version not in requirement.specifier:
            raise ValueError(f"Installed {name} does not satisfy {requirement}.")
        selected[name] = distribution.version
        identity = (name, tuple(sorted(requirement.extras)))
        if identity in seen:
            continue
        seen.add(identity)
        for value in distribution.requires or []:
            dependency = Requirement(value)
            extras = requirement.extras or {""}
            if dependency.marker is None or any(
                dependency.marker.evaluate({"extra": extra}) for extra in extras
            ):
                pending.append(dependency)
    return selected


def write_lock(name: str, selected: dict[str, str], base: dict[str, str] | None = None) -> None:
    """Write a resolved closure, optionally referencing the shared base lock."""
    lines = ["# Generated by scripts/lock-backend.py from verified installed metadata."]
    if base is not None:
        lines.append("-r base.txt")
    for package, version in sorted(selected.items()):
        if base is None or package not in base:
            lines.append(f"{package}=={version}")
    (REQUIREMENTS / name).write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    base_inputs = direct_requirements("base.in")
    base = closure(base_inputs)
    write_lock("base.txt", base)
    write_lock("dev.txt", closure(base_inputs + direct_requirements("dev.in")), base)
    write_lock("production.txt", closure(base_inputs + direct_requirements("production.in")), base)
    print("Resolved base/dev/production version locks written inside backend/requirements.")
